-- ── profiles: rol (ADMIN/USER) de cada usuario autenticado ────────────────────────
create table if not exists public.profiles (
  id uuid primary key references auth.users (id),
  full_name text,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
  on public.profiles for select
  to authenticated
  using (id = auth.uid());

-- private.is_admin(): SECURITY DEFINER para poder chequear el rol ADMIN desde una política
-- RLS de profiles sin caer en recursión infinita al volver a consultar la propia tabla.
create or replace function private.is_admin()
returns boolean
language sql
stable security definer
set search_path to 'public'
as $function$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'ADMIN'
  );
$function$;

drop policy if exists "Admins can read all profiles" on public.profiles;
create policy "Admins can read all profiles"
  on public.profiles for select
  to authenticated
  using (private.is_admin());

-- Al crearse un usuario nuevo en auth.users, se le crea automáticamente su fila en profiles.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.email),
    'USER'
  )
  on conflict (id) do nothing;
  return new;
end;
$function$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ── ai_usage: panel "Consumo IA" — tokens y costo estimado por llamada a OpenAI ────
create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users (id),
  user_email text,
  action text not null,
  stage text,
  model text not null,
  input_tokens bigint not null default 0,
  cached_input_tokens bigint not null default 0,
  output_tokens bigint not null default 0,
  total_tokens bigint not null default 0,
  estimated_cost_usd numeric not null default 0,
  response_id text,
  topic text,
  file_count integer not null default 0,
  file_names text[],
  metadata jsonb
);
alter table public.ai_usage enable row level security;
-- Sin políticas: solo accesible vía service_role desde la Edge Function "drive".

create index if not exists ai_usage_created_at_idx on public.ai_usage using btree (created_at desc);
create index if not exists ai_usage_user_id_idx on public.ai_usage using btree (user_id);
create index if not exists ai_usage_action_idx on public.ai_usage using btree (action);
