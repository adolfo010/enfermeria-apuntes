-- ── Esquema privado: funciones de seguridad que no se exponen por la API de datos ──
create schema if not exists private;

-- ── oauth_tokens: token de Google Drive, fila única compartida (id = 'rossana') ────
create table if not exists public.oauth_tokens (
  id text primary key default 'rossana',
  access_token text,
  refresh_token text,
  expires_at timestamptz,
  updated_at timestamptz not null default now()
